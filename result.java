package java_practice_task1;

public class result {

	void calculateResult(int sub1,int sub2) {
		int total=sub1+sub2;
		double Avg = total/2.0;
		System.out.println("Total of two subject: " +total);
		System.out.println("the avg of two subject: "+ Avg);
		
	}
	
	void calculateResult(int sub1,int sub2,int sub3) {
		int total=sub1+sub2+sub3;
		double Avg = total/3.0;
		System.out.println("Total of two subject: " +total);
		System.out.println("the avg of two subject: "+ Avg);
		
	}
	
	void calculateResult(int sub1,int sub2,int sub3,int sub4,int sub5) {
		int total=sub1+sub2+sub3+sub4+sub5;
		double Avg = total/5.0;
		System.out.println("Total of two subject: " +total);
		System.out.println("the avg of two subject: "+ Avg);
		
	}
}
